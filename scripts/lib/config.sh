#!/usr/bin/env bash
# config.sh — TOML configuration generation for server, client, and permissions.
#
# Sourced by setup.sh; do not execute directly.
# Requires: common.sh (for toml_escape, toml_key, DEFAULT_DATA_DIR)
# Expects from caller: INSTALL_MODE, IRC_SERVER_PASS, IRC_SERVER_PASS_TOML,
#   LLM_PROVIDER_ID, LLM_API_BASE, LLM_MODEL, ADMIN_NICK_TOML, ADMIN_NICK_KEY,
#   BUS_KEY, VAULT_PASS, DASHBOARD_ENABLED, DASHBOARD_PORT, SEARCH_PROVIDER,
#   TOOL_SHELL, TOOL_CODE_EXEC, TOOL_RSS, TOOL_DNS, TOOL_HTTP,
#   TOOL_IRC_MANAGE, TOOL_CONFIG_MANAGE, TOOL_SYSTEMINFO, TOOL_SEARXNG,
#   TOOL_BROWSER, TOOL_OPENCODE, OPER_PASS, OPENCODE_API_KEY,
#   RAG_ENABLED, SUMMARY_MODEL (for server config)
# Additional for client: CLIENT_ID, CLIENT_HOSTNAME, CLIENT_AUTONOMY,
#   IRC_PASSWORD_TOML, CLIENT_NICK_SAFE, BUS_KEY_TOML, VAULT_ENABLED,
#   CT_* flags, API_ENABLED (for standalone client config)

# ─── Generate server config ─────────────────────────────────────────────────

generate_server_config() {
	local irc_server irc_port irc_tls data_dir config_path vault_db_path memory_db_path
	local system_prompt_path permissions_path

	if [[ "$INSTALL_MODE" == "docker" ]]; then
		irc_server="ircd"
		irc_port="6667"
		irc_tls="false"
		data_dir="/data"
		config_path="/etc/murmur/server.toml"
		vault_db_path="/data/vault.db"
		memory_db_path="/data/memory.db"
		system_prompt_path="/data/system_prompt.md"
		permissions_path="/data/permissions.toml"
	else
		irc_server="localhost"
		irc_port="6667"
		irc_tls="false"
		data_dir="$DEFAULT_DATA_DIR"
		config_path="$DEFAULT_DATA_DIR/server.toml"
		vault_db_path="$DEFAULT_DATA_DIR/vault.db"
		memory_db_path="$DEFAULT_DATA_DIR/memory.db"
		system_prompt_path="$DEFAULT_DATA_DIR/system_prompt.md"
		permissions_path="$DEFAULT_DATA_DIR/permissions.toml"
	fi

	local irc_password_line=""
	if [[ -n "$IRC_SERVER_PASS" ]]; then
		irc_password_line="password = \"$IRC_SERVER_PASS_TOML\""
	else
		irc_password_line="# password = \"\""
	fi

	# Build OPER config lines
	local oper_lines=""
	if [[ -n "${OPER_PASS:-}" ]]; then
		oper_lines="oper_user = \"admin\"
oper_password = \"vault:oper-password\""
	else
		oper_lines="# oper_user = \"admin\"
# oper_password = \"vault:oper-password\""
	fi

	cat <<TOML
# Murmur server configuration — generated by setup wizard

[server]
data_dir = "$data_dir"
system_prompt_file = "$system_prompt_path"
name = "server"
verbose = true

[irc]
server = "$irc_server"
port = $irc_port
tls = $irc_tls
nick = "murmur"
user = "murmur"
realname = "Murmur Agent"
$irc_password_line
nickserv_password = "vault:nickserv-password"
$oper_lines
max_line_len = 8192

[irc.channels]
main = "#murmur"
bus = "#murmur-bus"

[llm]
default = "$LLM_PROVIDER_ID"

[llm.providers.$LLM_PROVIDER_ID]
api_base = "$LLM_API_BASE"
api_key = "vault:llm-api-key"
model = "$(toml_escape "$LLM_MODEL")"
max_tokens = 8192
temperature = 0.7

[memory]
db_path = "$memory_db_path"
max_history = 100
TOML

	# Summary model (optional)
	if [[ -n "${SUMMARY_MODEL:-}" ]]; then
		cat <<TOML
summary_model = "$(toml_escape "$SUMMARY_MODEL")"
TOML
	fi

	# RAG memory search
	if [[ "${RAG_ENABLED:-false}" == "true" ]]; then
		cat <<'TOML'

[memory.rag]
enabled = true
auto_ingest_summaries = true
TOML
	fi

	cat <<TOML

[scheduler]
enabled = true
heartbeat_interval = "5m"
client_timeout = "2m"
tick_interval = "30s"
max_concurrent = 3

[security]
allowed_users = ["$ADMIN_NICK_TOML"]
require_nickserv = true
bus_key = "$BUS_KEY"
permissions_file = "$permissions_path"

[vault]
enabled = true
db_path = "$vault_db_path"
passphrase_env = "MURMUR_VAULT_PASS"
TOML

	# Server-side tools
	if [[ "$TOOL_SHELL" == "true" ]]; then
		if [[ "$INSTALL_MODE" == "docker" ]]; then
			cat <<'TOML'

[tools.shell]
enabled = true
docker_image = "murmur-shell:latest"
network = true
memory_limit = "256m"
cpu_limit = "1.0"
timeout = "60s"
TOML
		else
			cat <<'TOML'

[tools.shell]
enabled = true
docker_image = "ubuntu:24.04"
network = false
memory_limit = "256m"
cpu_limit = "0.5"
timeout = "30s"
TOML
		fi
	fi

	if [[ "$TOOL_CODE_EXEC" == "true" ]]; then
		local piston_url
		if [[ "$INSTALL_MODE" == "docker" ]]; then
			piston_url="http://piston:2000"
		else
			piston_url="http://localhost:2000"
		fi
		cat <<TOML

[tools.code_exec]
enabled = true
piston_url = "$piston_url"
default_language = "python"
TOML
	fi

	if [[ "$TOOL_RSS" == "true" ]]; then
		cat <<'TOML'

[tools.rss]
enabled = true
max_items = 10
TOML
	fi

	if [[ "$TOOL_DNS" == "true" ]]; then
		cat <<'TOML'

[tools.dns]
enabled = true
TOML
	fi

	if [[ "$TOOL_HTTP" == "true" ]]; then
		cat <<'TOML'

[tools.http]
enabled = true
timeout = "30s"
max_response_bytes = 1048576
block_private_ips = true
TOML
	fi

	if [[ "${TOOL_SYSTEMINFO:-false}" == "true" ]]; then
		cat <<'TOML'

[tools.systeminfo]
enabled = true
TOML
	fi

	if [[ "${TOOL_SEARXNG:-false}" == "true" || "$SEARCH_PROVIDER" == "searxng" ]]; then
		local searxng_url
		if [[ "$INSTALL_MODE" == "docker" ]]; then
			searxng_url="http://searxng:8080"
		else
			searxng_url="http://localhost:8080"
		fi
		cat <<TOML

[tools.searxng]
enabled = true
url = "$searxng_url"
max_results = 10
TOML
	elif [[ "$SEARCH_PROVIDER" == "brave" ]]; then
		cat <<'TOML'

[tools.web_search]
enabled = true
api_key = "vault:brave-search-key"
max_results = 5
TOML
	fi

	if [[ "${TOOL_BROWSER:-false}" == "true" ]]; then
		local browser_endpoint
		if [[ "$INSTALL_MODE" == "docker" ]]; then
			browser_endpoint="http://browser:3001"
		else
			browser_endpoint="http://localhost:3001"
		fi
		cat <<TOML

[tools.browser]
enabled = true
endpoint = "$browser_endpoint"
TOML
	fi

	if [[ "${TOOL_OPENCODE:-false}" == "true" ]]; then
		local opencode_url
		if [[ "$INSTALL_MODE" == "docker" ]]; then
			opencode_url="http://opencode:3000"
		else
			opencode_url="http://localhost:3000"
		fi
		cat <<TOML

[tools.opencode]
enabled = true
url = "$opencode_url"
TOML
	fi

	if [[ "$TOOL_CONFIG_MANAGE" == "true" ]]; then
		cat <<TOML

[tools.config_manage]
enabled = true
config_path = "$config_path"
TOML
	fi

	if [[ "$TOOL_IRC_MANAGE" == "true" ]]; then
		cat <<'TOML'

[tools.irc_manage]
enabled = true
TOML
	fi

	# API
	cat <<TOML

[api]
enabled = true
listen = "0.0.0.0:8080"
api_key = "vault:api-key"
event_retention_days = 30
TOML

	# Dashboard
	if [[ "$DASHBOARD_ENABLED" == "true" ]]; then
		cat <<TOML

[dashboard]
enabled = true
listen = "0.0.0.0:$DASHBOARD_PORT"
TOML
		# Auto-populate server_password so dashboard users don't need to know it
		if [[ -n "$IRC_SERVER_PASS" ]]; then
			cat <<'TOML'
server_password = "vault:irc-server-password"
TOML
		fi
	fi

	# Debug (commented out)
	cat <<'TOML'

# [debug]
# enabled = true
# channel = "#murmur-debug"
# log_level = "debug"
# log_tool_calls = true
# log_llm_requests = true
# log_permissions = true
TOML
}

# ─── Generate client config (co-located with server) ────────────────────────

