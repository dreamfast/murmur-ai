[vault]
enabled = true
db_path = "$vault_db_path"
passphrase_env = "MURMUR_VAULT_PASS"

[tools.systeminfo]
enabled = true
TOML

	if [[ "$TOOL_SHELL" == "true" ]]; then
		if [[ "$INSTALL_MODE" == "docker" ]]; then
			cat <<'TOML'

[tools.shell]
enabled = true
docker_image = "murmur-shell:latest"
network = true
memory_limit = "256m"
cpu_limit = "1.0"
timeout = "60s"
TOML
		else
			cat <<'TOML'

[tools.shell]
enabled = true
docker_image = "ubuntu:24.04"
network = false
memory_limit = "256m"
cpu_limit = "0.5"
timeout = "30s"
TOML
